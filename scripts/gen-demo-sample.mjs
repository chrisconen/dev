// Generates a throwaway-signed sample AXR receipt for the /axr/start "Seal &
// Tamper" demo. The signature is produced over the SAME canonicalisation the
// in-browser verifier uses (src/lib/canonical.js -> stableStringify), so the
// page's verifySig() accepts it byte-for-byte. The key is disposable and exists
// only to make the demo's tamper check real rather than faked.
//
// Run:  node scripts/gen-demo-sample.mjs   (writes src/lib/axr-demo.ts)
//
// The editable demo fields are intentionally strings, so retyping the exact
// original value re-forges the seal (string === string), no type coercion.

import crypto from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { stableStringify } from '../src/lib/canonical.js';

const __dirname = dirname(fileURLToPath(import.meta.url));

// The receipt body (no volatile fields). signablePart() strips only
// signature/anchor_ref/redactable/witness_cosignatures, none of which are here,
// so signablePart(full) === this body and the bytes match what we sign.
const body = {
  axr_version: '0.2',
  receipt_type: 'step',
  receipt_id: 'rcpt_demo_5f3a9c',
  workflow_receipt_id: 'wf_demo_5f3a9c',
  sequence: 5,
  timestamp: '2026-06-26T09:14:22Z',
  agent_id: 'axr:agent:eco-clean:v5.2',
  step: {
    node_name: 'Create Booking',
    node_type: 'n8n-nodes-base.googleCalendar',
    logic_version: '5.2 HU',
    deterministic: true,
  },
  io: {
    input_summary: {
      customer: 'A. Nagy',
      service: 'Carpet clean',
      date: '2026-07-02',
      price: '38000',
    },
    decision: 'BOOKING_CONFIRMED',
  },
  previous_receipt_hash: 'sha256:5c10e8a1d9f3b27744a0c6e1b8f209d4a17c3e55b9026d8841fb73ac9e120d9f3',
};

const { privateKey, publicKey } = crypto.generateKeyPairSync('ed25519');
const message = Buffer.from(stableStringify(body), 'utf8');
const signature = crypto.sign(null, message, privateKey).toString('base64');
const pubPem = publicKey.export({ type: 'spki', format: 'pem' }).toString().trim();

const full = { ...body, signature };

// sanity check: verify with node before we ship it
const ok = crypto.verify(null, message, publicKey, Buffer.from(signature, 'base64'));
if (!ok) {
  console.error('FATAL: self-verify failed');
  process.exit(1);
}

const out =
  `// AUTO-GENERATED by scripts/gen-demo-sample.mjs — DO NOT EDIT BY HAND.\n` +
  `// A sample AXR step receipt signed with a disposable Ed25519 key, so the\n` +
  `// /axr/start "Seal & Tamper" demo runs a real signature check (not a fake).\n` +
  `// Regenerate with: node scripts/gen-demo-sample.mjs\n\n` +
  `export const SAMPLE_PUBKEY_PEM = ${JSON.stringify(pubPem)};\n\n` +
  `export const SAMPLE_RECEIPT = ${JSON.stringify(full, null, 2)} as const;\n`;

writeFileSync(join(__dirname, '..', 'src', 'lib', 'axr-demo.ts'), out, 'utf8');
console.log('Wrote src/lib/axr-demo.ts — self-verify OK. Public key:\n' + pubPem);
